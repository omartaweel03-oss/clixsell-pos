const L = require('./lib.js'); const S = __dirname;
const { execSync } = require('child_process');
const q = (sql) => execSync(`python3 ${S}/q.py ${S}/clixsell.db "${sql}"`).toString().trim();
const num = (sql) => +q(sql).replace(/[^0-9.]/g, '');
let pass = 0, fail = 0; const ok = (name, c, info = '') => { c ? pass++ : fail++; console.log(c ? 'PASS' : 'FAIL', name, info); };
const btn = async (p, name, exact = false) => { const l = exact ? p.getByRole('button', { name, exact: true }) : p.getByRole('button').filter({ hasText: name }); await l.first().click({ timeout: 8000 }); await p.waitForTimeout(1300); };
const txt = async (p) => await p.locator('flt-semantics-host').innerText();
(async () => {
  // ── 1. cashier: suspend from POS, stock unchanged ──
  let h = await L.start(S, 1440, 1000); let p = h.p;
  await h.login('shini.cashier', 'Cashier-Pass-1');
  const milk0 = num("select quantity from products where product_id=9"), water0 = num("select quantity from products where product_id=10");
  await btn(p, 'Mineral Water'); await btn(p, 'Mineral Water'); await btn(p, "Palestinian Za'atar");
  await btn(p, 'Suspend Invoice');
  const [sid, inv, st, tot, sub, tax] = q("select sale_id,invoice_number,status,total,subtotal,tax from sales where store_id=1 order by sale_id desc limit 1").replace(/[()']/g, '').split(', ');
  ok('1 suspend saved as SUSPENDED', st === 'SUSPENDED', inv);
  ok('1 total = (2x2.50 + 12.00) x 1.16 = 19.72', Math.abs(+tot - 19.72) < 0.001, `sub ${sub} tax ${tax} total ${tot}`);
  ok('1 suspend does not change stock', num("select quantity from products where product_id=9") === milk0 && num("select quantity from products where product_id=10") === water0);
  await btn(p, 'Suspended Invoices', true);
  let t = await txt(p);
  ok('1 row in screen with cashier, total, items', t.includes(inv) && t.includes('₪ 19.72') && t.includes('Lina Saleh') && /Cashier/.test(t), '');
  await h.shot('r1_cashier_en');
  // ── 2. resume from screen -> POS -> complete: same number, stock down ──
  await p.getByRole('button', { name: 'Resume in POS' }).first().click(); await p.waitForTimeout(1500);
  t = await txt(p); ok('2 resume opens POS with the invoice', t.includes('Complete Sale') && t.includes(inv), '');
  await h.shot('r2_resumed_pos');
  await btn(p, 'Complete Sale'); await p.waitForTimeout(1200);
  const r2 = q(`select invoice_number,status,total from sales where sale_id=${sid}`);
  ok('2 completed with the same number', r2.includes(inv) && r2.includes('COMPLETED'), r2);
  ok('2 stock decreased (water -2, zaatar -1)', num("select quantity from products where product_id=9") === milk0 - 1 && num("select quantity from products where product_id=10") === water0 - 2);
  ok('2 one invoice row only (no duplicate)', q(`select count(*) from sales where invoice_number='${inv}'`) === '(1,)');
  await btn(p, 'New Invoice', true).catch(() => {});
  // ── 3. suspend another, delete from screen: CANCELED, kept, stock unchanged ──
  await btn(p, 'Palestinian Olive Oil'); await btn(p, 'Suspend Invoice');
  const [sid3, inv3] = q("select sale_id,invoice_number from sales where store_id=1 order by sale_id desc limit 1").replace(/[()']/g, '').split(', ');
  const bread0 = num("select quantity from products where product_id=7");
  await btn(p, 'Suspended Invoices', true);
  await p.getByRole('button', { name: 'Delete (cancel)' }).first().click(); await p.waitForTimeout(800);
  await btn(p, 'Keep invoice', true).catch(async () => { await p.keyboard.press('Escape'); });
  ok('3 cancel in confirm keeps it', q(`select status from sales where sale_id=${sid3}`).includes('SUSPENDED'));
  await p.getByRole('button', { name: 'Delete (cancel)' }).first().click(); await p.waitForTimeout(800);
  await h.shot('r3_delete_confirm');
  await p.getByRole('button', { name: 'Delete', exact: true }).last().click(); await p.waitForTimeout(1500);
  ok('3 delete -> CANCELED and kept with lines', q(`select status from sales where sale_id=${sid3}`).includes('CANCELED') && q(`select count(*) from sale_items where sale_id=${sid3}`) === '(1,)');
  ok('3 stock unchanged', num("select quantity from products where product_id=7") === bread0);
  await p.waitForTimeout(5000); await p.getByRole('button', { name: 'Refresh' }).click(); await p.waitForTimeout(1500);
  t = await txt(p); ok('3 removed from list', !t.includes(inv3));
  await h.b.close();
  // ── 4. pages + filters (25 more via the real API as the cashier) ──
  const tok = JSON.parse(execSync(`curl -s -X POST localhost:8080/api/auth/login -H 'Content-Type: application/json' -d '{"username":"shini.cashier","password":"Cashier-Pass-1"}'`)).token;
  for (let i = 0; i < 25; i++) execSync(`curl -s -X POST localhost:8080/api/sales/suspended -H 'Content-Type: application/json' -H 'Authorization: Bearer ${tok}' -d '{"items":[{"productId":10,"quantity":1}]}'`);
  const n = +q("select count(*) from sales where store_id=1 and status='SUSPENDED'").replace(/\D/g, '');
  h = await L.start(S, 1440, 1000); p = h.p;
  await h.login('shini.admin', 'Admin-Pass-1');
  await btn(p, 'Suspended Invoices', true);
  t = await txt(p);
  ok(`4 count card = DB (${n})`, t.includes(`Showing 1 – 10 of ${n} invoices`), t.match(/Showing[^\n]*/)?.[0]);
  await p.getByRole('button', { name: 'Next page' }).click().catch(async () => { await btn(p, '2', true); }); await p.waitForTimeout(800);
  t = await txt(p); ok('4 next page', t.includes(`Showing 11 – 20 of ${n}`), t.match(/Showing[^\n]*/)?.[0]);
  await btn(p, '3', true); t = await txt(p); ok('4 page 3', t.includes(`Showing 21 – ${n} of ${n}`), t.match(/Showing[^\n]*/)?.[0]);
  await h.shot('r4_page3');
  await p.getByRole('button', { name: '10 per page' }).click({ timeout: 8000 }); await p.waitForTimeout(600);
  await p.getByRole('menuitem', { name: '50 per page' }).click({ timeout: 8000 }); await p.waitForTimeout(800);
  t = await txt(p); ok('4 50 per page', t.includes(`Showing 1 – ${n} of ${n}`), t.match(/Showing[^\n]*/)?.[0]);
  await p.getByRole('button', { name: 'All months' }).click({ timeout: 8000 }); await p.waitForTimeout(600);
  await p.getByRole('menuitem', { name: 'October' }).click({ timeout: 8000 }); await p.waitForTimeout(800);
  t = await txt(p); ok('4 month filter: October has none of this store', t.includes('No suspended invoices in this month') || /0\s*\n/.test(t), '');
  await h.shot('r5_month_empty');
  await p.getByRole('button', { name: 'October' }).click({ timeout: 8000 }); await p.waitForTimeout(600);
  await p.getByRole('menuitem', { name: 'November' }).click({ timeout: 8000 }); await p.waitForTimeout(800);
  t = await txt(p); ok('4 month filter: November shows all', t.includes(`of ${n} invoices`));
  // Arabic
  await btn(p, 'العربية'); await p.waitForTimeout(1200);
  t = await txt(p); ok('5 Arabic labels', t.includes('الكاشير') && t.includes('رمز الفاتورة') && t.includes('أقدم فاتورة معلقة'), '');
  await h.shot('r6_admin_ar');
  await p.setViewportSize({ width: 1024, height: 768 }); await p.waitForTimeout(1200); await h.shot('r7_ar_1024');
  await p.setViewportSize({ width: 390, height: 844 }); await p.waitForTimeout(1200); await h.shot('r8_ar_390');
  await btn(p, 'English').catch(() => {});
  await p.setViewportSize({ width: 1024, height: 768 }); await p.waitForTimeout(1200); await h.shot('r9_en_1024');
  await h.b.close();
  // ── 6. other store + sysadmin ──
  h = await L.start(S, 1440, 1000); p = h.p;
  await h.login('neshan.admin', 'Admin-Pass-1');
  await btn(p, 'Suspended Invoices', true);
  t = await txt(p); ok('6 Neshan sees no Shini invoices', !t.includes('Lina Saleh') && !t.includes(inv3));
  await h.shot('r10_neshan');
  await h.b.close();
  const ntok = JSON.parse(execSync(`curl -s -X POST localhost:8080/api/auth/login -H 'Content-Type: application/json' -d '{"username":"neshan.admin","password":"Admin-Pass-1"}'`)).token;
  const anyShini = q("select sale_id from sales where store_id=1 and status='SUSPENDED' limit 1").replace(/\D/g, '');
  const code = execSync(`curl -s -o /dev/null -w '%{http_code}' -X DELETE localhost:8080/api/sales/suspended/${anyShini} -H 'Authorization: Bearer ${ntok}'`).toString();
  ok('6 Neshan cannot delete Shini invoice (404)', code === '404', code);
  h = await L.start(S, 1440, 1000); p = h.p;
  await h.login('sysadmin', 'Admin12345');
  t = await txt(p); ok('7 System Admin has no Suspended Invoices item', !t.includes('Suspended Invoices'));
  await h.b.close();
  console.log(`\nE2E PASS ${pass} FAIL ${fail}`);
})().catch(e => console.log('ERR', e.message.split('\n')[0]));
